    literate_abstract(Primes, Correlation, Abstract),
    literate_prime_lattice(Primes, Lattice),
    literate_heat_theorem(HeatData, Correlation, HeatThm),
    literate_executable_code(Code),
    literate_conclusion(Conclusion),
    
    atomic_list_concat([
        Preamble, Abstract, Lattice, HeatThm, Code, Conclusion
    ], '\n\n', Document),
    
    open('generated/monster_literate.nw', write, Stream),
    write(Stream, Document),
    close(Stream),
    
    format('✅ Literate report: generated/monster_literate.nw~n', []).

